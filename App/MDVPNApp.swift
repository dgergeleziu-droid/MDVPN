// App/MDVPNApp.swift
// НАЗНАЧЕНИЕ: точка входа приложения.
// ЧТО ДЕЛАЕТ: создаёт единственный экземпляр VPNViewModel
//             и прокидывает его во все дочерние View через Environment.
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ: чтобы не смешивать жизненный цикл
//                       с UI-логикой и не искать точку входа по всему проекту.

import SwiftUI   // нужен для App, Scene, WindowGroup

@main   // говорит компилятору: "вот здесь стартует приложение"
struct MDVPNApp: App {   // структура-приложение, реализует протокол App

    // @StateObject — создаёт объект ОДИН РАЗ и хранит, пока приложение живо.
    // Если бы стоял @State с классом — ViewModel пересоздавалась бы при перерисовках.
    @StateObject private var vpn = VPNViewModel()

    // body — описание того, какие окна открывает приложение.
    var body: some Scene {
        // WindowGroup — на iPhone это одно окно. На iPad/Mac — может быть много.
        WindowGroup {
            // Корневой экран. От него строится вся иерархия.
            MainVPNView()
                // Прокидываем ViewModel вниз по дереву.
                // Любая вложенная View может достать её через @EnvironmentObject.
                .environmentObject(vpn)
                // Принудительно тёмная тема — чтобы системные элементы
                // (sheet, клавиатура, статус-бар) совпадали с нашим фоном.
                .preferredColorScheme(.dark)
        }
    }
}
